-- Закрытие дня техником: он вводит свою зарплату за день и бензин со своего телефона, а суммы
-- попадают в тот же гроссбух расходов, что и записи администратора.
--
-- Отдельную таблицу заводить не стали сознательно: это расходы той же природы, категории FUEL и
-- SALARY в business_expenses уже есть, и все отчёты (чистая прибыль, месячный xlsx, сводка)
-- читают именно этот гроссбух. Пиши мы в отдельную таблицу — пришлось бы складывать два источника
-- в каждом отчёте, и любая новая витрина рисковала бы забыть про второй.
--
-- Два новых поля разделяют то, что раньше смешивалось в created_by:
--
--   staff_id   — ЧЬИ это деньги: кому зарплата, кто заправлялся. Когда владелец вносит зарплату
--                за Фёдора, created_by — владелец, и расход по технику не посчитать. С этим полем
--                появляется разрез затрат по человеку, который стыкуется с отчётом эффективности:
--                видно не только сколько техник заработал, но и сколько на него потрачено.
--   source     — ADMIN или TECHNICIAN. Запись бухгалтера — подтверждённый факт, запись техника —
--                самоотчёт. В отчётах они считаются одинаково (владелец просил «как сейчас»), но
--                в интерфейсе затрат различаются, чтобы задвоение было видно сразу.
--
-- Обе колонки допускают NULL/значение по умолчанию, поэтому исторические записи не трогаются:
-- у них staff_id остаётся пустым (неизвестно, за кого), а source — ADMIN.

CREATE TYPE expense_source AS ENUM ('ADMIN', 'TECHNICIAN');

ALTER TABLE business_expenses
    ADD COLUMN staff_id BIGINT REFERENCES staff (id),
    ADD COLUMN source   expense_source NOT NULL DEFAULT 'ADMIN';

COMMENT ON COLUMN business_expenses.staff_id IS
    'Чьи это деньги: кому зарплата, кто заправлялся. Отличается от created_by — кто внёс запись.';
COMMENT ON COLUMN business_expenses.source IS
    'ADMIN — запись владельца, TECHNICIAN — самоотчёт техника при закрытии дня.';

CREATE INDEX business_expenses_staff_idx ON business_expenses (staff_id, expense_date);

-- Защита от двойного ввода с телефона: техник нажал «Сохранить» дважды, или отправил повторно
-- после потери связи, или офлайн-очередь доставила запись второй раз. Натуральный ключ самоотчёта
-- — «техник + дата + категория», и повторная отправка обязана перезаписывать сумму, а не добавлять
-- вторую строку. Записей администратора ограничение не касается: он может вносить хоть десять
-- заправок за день.
CREATE UNIQUE INDEX business_expenses_technician_day_unique
    ON business_expenses (staff_id, expense_date, category)
    WHERE source = 'TECHNICIAN';
