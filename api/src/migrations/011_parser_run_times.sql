-- Владелец попросил парсер ходить в iVend 2 раза в сутки вместо раза в 5 минут (2.apixspb.ru —
-- 151к+ строк cashless_transactions накопилось от круглосуточного опроса) и хочет сам менять время
-- через страницу «Безнал», без правки кода. schedule_cron существовала с самого начала, но ни один
-- код её не читал (планировщик в server.ts был жёстко зашит на 5 минут) — используем её под простой
-- формат "HH:MM;HH:MM" (московское время, без секунд/полного cron-синтаксиса, который владельцу не
-- нужен объяснять), не добавляя отдельную колонку. 07:00 и 19:00 — до открытия точек и после закрытия,
-- разумные значения по умолчанию, редактируемые владельцем сразу после раскатки.
ALTER TABLE parser_settings ALTER COLUMN schedule_cron SET DEFAULT '07:00;19:00';
UPDATE parser_settings SET schedule_cron = '07:00;19:00' WHERE provider = 'ivend';
