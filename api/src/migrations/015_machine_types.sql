-- Справочник типов аппаратов. До этого тип хранился свободным текстом в machines.machine_type и
-- нигде не был перечислен: в проде накопилось четыре значения (МиникХ — 86 аппаратов, CRANE — 24,
-- Прищепка — 7, Хват — 2), то есть английский дефолт вперемешку с русскими названиями, которые
-- вводились руками при установке и легко расходились опечаткой.
--
-- Ссылка идёт по ИМЕНИ, а не по суррогатному id, намеренно. machines.machine_type уже TEXT, и все
-- существующие фильтры сравнивают его со строкой напрямую (domain/reports.ts, commands/toySets.ts).
-- Ключ по имени оставляет весь этот код нетронутым, а ON UPDATE CASCADE делает переименование типа
-- безопасным: оно само разъезжается по аппаратам одной операцией, без миграции данных. Запрет
-- удаления типа, который ещё используется, даёт стандартный RESTRICT внешнего ключа.
--
-- Триггера forbid_delete здесь намеренно нет, в отличие от финансовых таблиц: справочник не
-- является историей операций, и удалить ошибочно заведённый неиспользуемый тип должно быть можно.

CREATE TABLE machine_types (
    name       TEXT PRIMARY KEY,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Существующие значения переносятся как есть, без переименования: привести «CRANE» к русскому виду
-- это решение владельца, которое он теперь может принять сам через справочник.
INSERT INTO machine_types (name) SELECT DISTINCT machine_type FROM machines
ON CONFLICT (name) DO NOTHING;

-- Значение по умолчанию machines.machine_type должно существовать в справочнике ВСЕГДА, даже когда
-- аппаратов ещё нет. Иначе на чистой базе — а это не гипотетический случай, второй город
-- разворачивается отдельной установкой со своей БД — внешний ключ отверг бы дефолт, и установить
-- первый аппарат стало бы невозможно.
INSERT INTO machine_types (name) VALUES ('CRANE') ON CONFLICT (name) DO NOTHING;

ALTER TABLE machines ADD CONSTRAINT machines_machine_type_fkey
    FOREIGN KEY (machine_type) REFERENCES machine_types (name) ON UPDATE CASCADE;
