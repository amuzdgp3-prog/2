-- Признак полевого техника для отчёта по техникам (DECISION-046, DECISION-049).
--
-- Роль для этого не годится, и это выяснилось на боевых данных: учётная запись «Админ», под
-- которой при миграции залита вся историческая база (2681 обслуживание из 2821), имеет роль
-- TECHNICIAN — ровно как настоящие техники. Отчёт, отфильтрованный по роли, показал бы служебную
-- запись первой строкой и с отрывом, обесценив сравнение живых людей между собой.
--
-- По умолчанию TRUE: новый сотрудник с ролью техника — обычный полевой техник, и отдельного
-- действия при заведении не требуется. Служебные записи снимаются флагом вручную; на этой
-- установке это делается отдельным разовым UPDATE, а не здесь, потому что идентификатор служебной
-- записи специфичен для конкретного города, а миграция общая для всех установок.

ALTER TABLE staff ADD COLUMN is_field_technician BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN staff.is_field_technician IS
    'Учитывать ли сотрудника в отчёте по техникам. FALSE — служебная запись (миграция, интеграции).';
