-- Прочие расходы техника с фотографией чека.
--
-- Две правки, обе вытекают из того, как этими расходами пользуются на практике.
--
-- 1. Фото чека. Хранится в той же photo_objects, что и фотографии счётчиков: отдельное хранилище
--    ради чеков не нужно, а раздача файлов, права доступа и офлайн-выгрузка с телефона уже
--    работают. Ссылка необязательная: владелец разрешил сохранять трату без чека — техник мог
--    купить что-то там, где чека не дают, и запретить ему записать расход было бы хуже, чем
--    принять запись без подтверждения.
--
-- 2. Сужение уникального индекса из миграции 019 до зарплаты и бензина. Там он защищал от
--    двойного ввода: эти две величины естественно одни на день — дневная оплата и потраченный за
--    день бензин, и повторная отправка обязана перезаписывать. С прочими расходами всё наоборот:
--    за один день их может быть несколько (парковка, мойка, запчасть), у каждого свой чек и своё
--    назначение. Оставь мы индекс прежним, вторая трата за день просто не сохранилась бы.

ALTER TABLE business_expenses ADD COLUMN photo_object_key TEXT;

COMMENT ON COLUMN business_expenses.photo_object_key IS
    'Фото чека в photo_objects. NULL — трата без чека, это допустимо.';

DROP INDEX business_expenses_technician_day_unique;

CREATE UNIQUE INDEX business_expenses_technician_day_unique
    ON business_expenses (staff_id, expense_date, category)
    WHERE source = 'TECHNICIAN' AND category IN ('SALARY', 'FUEL');
